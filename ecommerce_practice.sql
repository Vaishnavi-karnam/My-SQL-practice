CREATE TABLE sales (
    order_id INT PRIMARY KEY,
    customer_name VARCHAR(50),
    product VARCHAR(50),
    category VARCHAR(30),
    quantity INT,
    unit_price DECIMAL(10,2),
    discount_percent INT,
    payment_method VARCHAR(30),
    city VARCHAR(50),
    order_date DATE,
    order_status VARCHAR(20)
);
